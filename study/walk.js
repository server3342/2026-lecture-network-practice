  function lenOf(p) {
    var L = 0;
    for (var i = 1; i < p.length; i++) L += Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1]);
    return L;
  }
  function at(p, d) {
    for (var i = 1; i < p.length; i++) {
      var sl = Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1]);
      if (d <= sl || i === p.length - 1) {
        var r = sl ? Math.min(d / sl, 1) : 1;
        return [p[i - 1][0] + (p[i][0] - p[i - 1][0]) * r, p[i - 1][1] + (p[i][1] - p[i - 1][1]) * r];
      }
      d -= sl;
    }
    return p[p.length - 1];
  }
